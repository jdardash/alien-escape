/**
 * `bmbr_stg_cfg_lut` -- how the DIP rank picks a sub-table
 * (new_stage.s:124-128).
 *
 * The rank value does not index the sub-tables directly: it goes through this
 * rotation, so rank value 3 plays the easiest sub-table (0) and rank value 2
 * the hardest (3).
 */
export const RANK_TO_SUBTABLE = [1, 2, 3, 0];

/**
 * The machine's raw rank value for each of this codebase's logical ranks.
 *
 * The cabinet's rank letters are not in raw order: the display string table
 * `str_3A68` maps raw 0 to B, 1 to C, 2 to D and 3 to A -- the factory rank
 * A is raw value 3 (docs/rom-research/stage-init.md section 1). This
 * codebase's `DifficultyRank` counts the letters A-D as 0-3, so this LUT
 * converts a logical rank to the value the machine tables see.
 */
export const MACHINE_RANK_VALUES = [3, 0, 1, 2];

/**
 * The sub-table of `BMBR_STG_CFG_DAT` a RAW machine rank plays.
 *
 * This is the DIFFICULTY mapping, through the rotation LUT. It exists as a
 * named pair with `caravanRankIndex` because the two tables index differently
 * and conflating them is exactly the mistake the rotation invites. Net
 * effect through `MACHINE_RANK_VALUES`: logical rank A plays sub-table 0
 * (the easiest) and logical rank D sub-table 3 (the hardest).
 */
export function difficultySubTable(machineRank) {
  return RANK_TO_SUBTABLE[machineRank & 0x03];
}

/**
 * The row block of the fly-in caravan index table a RAW machine rank plays.
 *
 * The caravan table `d_combat_stg_dat_idx` is indexed `rank * 17` DIRECTLY,
 * with no rotation (gg1-3.s:1197). Task 4's caravan machine must use this
 * one, never `difficultySubTable`.
 */
export function caravanRankIndex(machineRank) {
  return machineRank & 0x03;
}

