/**
 * `d_0909` and `d_0929` as the ROM keeps them: one contiguous table
 * (game_ctrl.s:1527-1539).
 *
 * First 32 bytes: `d_0909`, the bomb-drop enable bitmask, 8 rows x 4 columns,
 * row = stage parameter [0], column = live bugs / 10. Last 12 bytes:
 * `d_0929`, the boss reload, 3 rows x 4 columns at offset 0x20, row = stage
 * parameter [1], same column rule.
 *
 * They must stay one flat array: with 40 bugs the column is 4, and `c_08BE`
 * deliberately reads one byte past the row -- the next row's first byte, and
 * for `d_0909` row 7 that byte is `d_0929`'s first. The disassembly's own
 * comment at game_ctrl.s:1483-1488 confirms the layout is load-bearing.
 */
