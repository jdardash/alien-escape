/**
 * The byte the ROM reads when even the flat table overflows.
 *
 * `d_0929`'s last row with a full 40-bug board indexes one byte past the
 * table's end -- ROM address 0x0935, which is the first opcode of `f_0935`
 * (`ld a,(nn)` = 0x3A; game_ctrl.s:1553-1555). Only the hardest late-stage
 * rows (parameter [1] = 2) can reach it, and only at a full board.
 */
export const D_0909_0929_OVERRUN_BYTE = 0x3a;

/**
 * The initial per-type launch timers, in 16-frame ticks (new_stage.s:100-103).
 *
 * `c_2C00` hardcodes these for every stage and rank -- they are NOT in the
 * stage table. Boss 0x16 (~5.9 s), red and yellow 2 (~0.53 s): the red dives
 * first, the yellow immediately after, the boss much later. All later
 * cadence comes from the reload lookups recomputed every frame by `f_0857`.
 * Keys use this codebase's type names: red = Goei, yellow = Zako.
 */
export const INITIAL_LAUNCH_TICKS = { boss: 0x16, goei: 0x02, zako: 0x02 };

/**
 * Stage parameter [10], which is computed rather than packed
 * (new_stage.s:81-98): the clone-attack (transform trio) arming threshold.
 *
 * Zero -- transform disabled -- for stages 1-2 and for challenge stages
 * (`stage & 3 == 3` is the ROM's own challenge test); 0x0A everywhere else,
 * meaning the trio arms when the live bug count drops below ten.
 */
export function cloneAttackGate(stage) {
  if (stage < 3) return 0;
  if ((stage & 0x03) === 0x03) return 0;
  return 0x0a;
}

/**
 * The star scroll-control register value for a stage (new_stage.s:105-118).
 *
 * `c_2C00` ends by setting the starfield speed from the stage number, capped
 * at stage 0x10: `((min(stage, 0x10) << 2) & 0x70) + 0x40`.
 */
export function starSpeedControl(stage) {
  const capped = Math.min(Math.max(Math.trunc(stage), 0), 0x10);
  return ((capped << 2) & 0x70) + 0x40;
}

