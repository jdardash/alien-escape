/**
 * Where an object ID sits on the ROM's formation grid.
 *
 * `romRow` 0 is the phantom rogue/captured-ship row; rows 1-5 are the five
 * visible ranks (1 = bosses, 2-3 = butterflies, 4-5 = bees). `column` is
 * 0-9. Returns null for an ID off the 48-entry table.
 */
export function formationCellFor(objectId) {
  const offset = objectId & 0xfe;
  if (offset < 0 || offset >= SPRT_FMTN_HPOS.length) return null;
  return {
    romRow: (SPRT_FMTN_HPOS[offset] - 0x14) / 2,
    column: SPRT_FMTN_HPOS[offset + 1] / 2,
  };
}

/**
 * `d_2908` (gg1-3.s:1639-1640): the 44-bit fly-in bombing capability table,
 * MSB-first in roster order -- 20 bees 0x08-0x2E, 8 boss/bonus 0x30-0x3E,
 * 16 moths 0x40-0x5E. The bytes themselves are exported by
 * `difficultyData.js` (`D_2908_ENTRY_BOMB_BITS`); this is the per-object
 * decode `c_28E9` performs at stage init: whether this creature MAY bomb on
 * the way in. The stage's caravan `hdr1` mask is the second, stacked gate
 * (gg1-3.s:1796-1803).
 */
export function entryBombCapable(objectId) {
  let bit;
  if (objectId >= 0x08 && objectId <= 0x2e) bit = (objectId - 0x08) >> 1;
  else if (objectId >= 0x30 && objectId <= 0x3e) bit = 20 + ((objectId - 0x30) >> 1);
  else if (objectId >= 0x40 && objectId <= 0x5e) bit = 28 + ((objectId - 0x40) >> 1);
  else return false;

  const byte = D_2908_ENTRY_BOMB_BITS[bit >> 3];
  return (byte & (0x80 >> (bit & 7))) !== 0;
}
