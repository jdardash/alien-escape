/**
 * The ROM's flight-path tables, byte for byte.
 *
 * Every array in this file is a verbatim transcription of Galaga's own path
 * data, as recorded in `docs/rom-research/paths-motion.md` section 2 from the
 * hackbar_galaga disassembly (`gg1-5.s` / `gg1-3.s`) via the ZaneLogi corpus.
 * Nothing here is authored; the one representational liberty is that each
 * table is stored as a flat JS array with its Z80 base address alongside, so
 * the address arguments embedded in FD/FA/F0/F7/F2/EF tokens can be resolved
 * as `offset = addr - z80Base`. Data only -- the interpreter that runs these
 * bytes lives in `pathcode.js`.
 *
 * Encoding (paths-motion.md section 1.2): a byte below 0xEF opens a 3-byte
 * segment `[(vy << 4) | vx, signed rotRate, duration]`; a byte at or above
 * 0xEF is a control token. 0xFF ends a stream.
 */

/** First token opcode: any fetched byte at or above this dispatches. */
export const TOKEN_BASE = 0xef;

