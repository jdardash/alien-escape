/** The five wave-byte pairs of a challenge row, decoded out of the triplets. */
export function challengeRowWaves(row) {
  const waves = [];
  for (let wave = 0; wave < 5; wave += 1) {
    const base = 2 + wave * 3;
    waves.push({ transientCtl: row[base], m0: row[base + 1], m1: row[base + 2] });
  }
  return waves;
}
